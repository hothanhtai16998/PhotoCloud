const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const classes = new Set();
const listeners = new Map();
let queued, cleanup, interacting = false;
const header = { offsetHeight: 80, inert: false, querySelector: () => interacting ? {} : null, addEventListener() {}, removeEventListener() {} };
const window = { scrollY: 0, innerHeight: 800, addEventListener: (name, fn) => listeners.set(name, fn), removeEventListener: name => listeners.delete(name) };
const stage = { getBoundingClientRect: () => ({ bottom: 800 - window.scrollY }) };
const slider = { querySelector: () => stage };
const body = { classList: { add: name => classes.add(name), remove: (...names) => names.forEach(name => classes.delete(name)), contains: name => classes.has(name), toggle(name, on) { if (on) classes.add(name); else classes.delete(name); } }, hasAttribute: () => false };
const exportsObject = {};
const code = ts.transpileModule(fs.readFileSync('src/components/ImmersiveHomeChrome.tsx', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
vm.runInNewContext(code, { exports: exportsObject, require: name => name === 'react' ? { useLayoutEffect: fn => { cleanup = fn(); } } : {}, window, document: { body, querySelector: selector => selector === '.PHOTOCLOUD-header' ? header : slider }, requestAnimationFrame: fn => { queued = fn; return 1; }, cancelAnimationFrame: () => { queued = null; }, ResizeObserver: class { observe() {} disconnect() {} } });
exportsObject.ImmersiveHomeChrome();
function scroll(y) { window.scrollY = y; listeners.get('scroll')(); const fn = queued; queued = null; fn(); }
const hidden = () => classes.has('home-header-hidden');
assert.equal(hidden(), false);
scroll(700); assert.equal(hidden(), false); assert.equal(classes.has('home-cinematic-active'), true);
scroll(730); assert.equal(classes.has('home-cinematic-active'), false, 'solid background before header overlaps content');
scroll(780); assert.equal(hidden(), false);
scroll(850); assert.equal(hidden(), false, 'header stays accessible below the slide'); assert.equal(header.inert, false);
scroll(840); assert.equal(hidden(), false, 'header stays accessible below the slide');
scroll(820); assert.equal(hidden(), false); assert.equal(header.inert, false);
scroll(860); assert.equal(hidden(), false, 'small downward movement does not toggle');
scroll(880); assert.equal(hidden(), false, 'header stays accessible below the slide');
interacting = true; scroll(900); assert.equal(hidden(), false, 'open menu keeps header visible');
interacting = false; classes.add('scroll-locked'); scroll(1000); assert.equal(hidden(), false);
classes.delete('scroll-locked'); scroll(1060); assert.equal(hidden(), false, 'header stays accessible below the slide');
listeners.get('resize')(); queued(); queued = null; assert.equal(hidden(), false, 'header stays accessible below the slide');
scroll(0); assert.equal(hidden(), false); assert.equal(classes.has('home-cinematic-active'), true);
cleanup(); assert.equal(header.inert, false); assert.equal(classes.size, 0); assert.equal(listeners.size, 0);
console.log('Header checks passed: slide boundary, scroll thresholds, direction, menu, scroll lock, resize, cleanup.');
