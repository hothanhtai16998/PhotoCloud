const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const src = path.join(__dirname, '../src');
const compile = source => ts.transpileModule(source, {compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const storageContext={exports:{},window:{scrollY:1400}};
vm.runInNewContext(compile(fs.readFileSync(path.join(src,'utils/imagePageScroll.ts'),'utf8')),storageContext);
const positions=storageContext.exports;
const first={key:'first',pathname:'/photos/b',search:'',hash:''};
const second={...first,key:'second'};
positions.saveImagePageScroll(first,{scrollTop:350});
assert.equal(positions.getImagePageScroll(first).windowY,1400);
assert.equal(positions.getImagePageScroll(first).contentY,350);
assert.equal(positions.getImagePageScroll(second),undefined,'separate history entries must not share positions');
storageContext.window.scrollY=120;
positions.saveImagePageScroll(first,{scrollTop:0});
assert.equal(positions.getImagePageScroll(first).windowY,120,'reopening must overwrite the previous position');
for(let n=0;n<51;n++)positions.saveImagePageScroll({...first,key:String(n)},null);
assert.equal(positions.getImagePageScroll(first),undefined,'the cache must remain bounded');
const hook=compile(fs.readFileSync(path.join(src,'hooks/useImagePageScrollRestore.ts'),'utf8'));
function run(position, isBackground=false) {
  let cleanup,observer,windowY=0,contentY=0,windowMax=100,contentMax=100;
  const frames=new Map(),listeners=new Map();
  let next=0;
  const scroller={children:[{}],get scrollTop(){return contentY;},set scrollTop(value){contentY=Math.min(contentMax,value);}};
  const history={scrollRestoration:'auto'};
  const win={history,get scrollY(){return windowY;},scrollTo:({top})=>{windowY=Math.min(windowMax,top);},addEventListener:(name,fn)=>listeners.set(name,fn),removeEventListener:name=>listeners.delete(name)};
  const context={exports:{},require:name=>name==='react'?{useRef:()=>({current:undefined}),useLayoutEffect:fn=>{cleanup=fn();}}:{getImagePageScroll:()=>position},window:win,ResizeObserver:class{constructor(callback){this.callback=callback;observer=this;this.disconnected=false;}observe(){}disconnect(){this.disconnected=true;}},requestAnimationFrame:fn=>{frames.set(++next,fn);return next;},cancelAnimationFrame:id=>frames.delete(id)};
  vm.runInNewContext(hook,context);
  context.exports.useImagePageScrollRestore(first,{current:scroller},true,isBackground,'photo',20);
  const flush=()=>{const pending=[...frames.values()];frames.clear();pending.forEach(fn=>fn());};
  return {flush,cleanup,frames,listeners,observer,history,grow:()=>{windowMax=3000;contentMax=1000;observer.callback();},getWindowY:()=>windowY,getContentY:()=>contentY};
}
const delayed=run({windowY:1700,contentY:350});
delayed.flush();
assert.equal(delayed.history.scrollRestoration,'manual');
assert.equal(delayed.observer.disconnected,false,'wait while async content is too short');
delayed.grow();delayed.flush();
assert.equal(delayed.getWindowY(),1700);
assert.equal(delayed.getContentY(),350);
assert.equal(delayed.observer.disconnected,true);
assert.equal(delayed.listeners.size,0);
assert.equal(delayed.history.scrollRestoration,'auto');
const interrupted=run({windowY:1700,contentY:0});
interrupted.flush();interrupted.listeners.get('wheel')();
interrupted.grow();interrupted.flush();
assert.equal(interrupted.getWindowY(),100,'user input must cancel pending restoration');
const disposed=run({windowY:1700,contentY:0});
disposed.cleanup();disposed.flush();
assert.equal(disposed.getWindowY(),0);
assert.equal(disposed.frames.size,0);
assert.equal(disposed.listeners.size,0);
const background=run({windowY:1700,contentY:0},true);
background.flush();
assert.equal(background.listeners.size,0,'interacting with M must not cancel pending restoration of B');
background.grow();background.flush();
assert.equal(background.getWindowY(),1700);
console.log('Image scroll: entry isolation, overwrite, bounded cache, delayed content, both scrollers, user cancellation and cleanup passed.');
