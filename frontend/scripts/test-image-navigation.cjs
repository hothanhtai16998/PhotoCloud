const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.join(__dirname, '../src');
const transpile = source => ts.transpileModule(source, {compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const storage = new Map();
const sessionStorage = {getItem:key=>storage.get(key)||null,setItem:(key,value)=>storage.set(key,value),removeItem:key=>storage.delete(key)};
const history = {state:{idx:5,key:'photo-a',usr:{inlineModal:true}},replaceState(state){this.state=state;}};
const context = {exports:{},require:()=>({INLINE_MODAL_FLAG_KEY:'modal'}),window:{history,location:{pathname:'/photos/a',search:'?source=test',hash:'#details'}},document:{title:'PhotoCloud'},sessionStorage,performance:{getEntriesByType:()=>[{type:'reload'}]}};
vm.runInNewContext(transpile(fs.readFileSync(path.join(root,'utils/modalNavigation.ts'),'utf8')),context);
const utils=context.exports;
const photoA={_id:'000000000000000000000001',imageTitle:'A'};
const photoB={_id:'000000000000000000000002',imageTitle:'B'};
const home={pathname:'/',search:'?category=landscape',hash:'#grid',state:null,key:'home'};
const stale={pathname:'/photos/a',search:'?source=test',hash:'#details',key:'a',state:{inlineModal:true,background:home,image:photoA,images:[photoA,photoB]}};
utils.setModalActive();
utils.clearModalStateOnRefresh();
assert.equal(utils.validateModalState(stale.state).isValid,false);
assert.equal(utils.getImageNavigationBackground(stale).pathname,'/photos/a','invalid stale background must not become home again');
const app=fs.readFileSync(path.join(root,'App.tsx'),'utf8');
const start=app.indexOf('  // Clean up invalid modal state');
const normalization=app.slice(start,app.indexOf('  // Mobile uses a single full page',start));
let normalized;
vm.runInNewContext(transpile(normalization),{useEffect:fn=>fn(),location:stale,reloadLocationKey:stale.key,clearModalStateOnRefresh:utils.clearModalStateOnRefresh,modalValidation:{isValid:false},navigate:(url,options)=>{normalized={url,options};},withoutModalState:utils.withoutModalState});
assert.equal(normalized.url,'/photos/a?source=test#details');
assert.equal(normalized.options.replace,true);
assert.equal(history.state.idx,5,'normalization must leave history indexing to Router');
assert.equal(normalized.options.state.background,undefined,'Router state must also discard home background');
const page=fs.readFileSync(path.join(root,'pages/image/useImagePageController.ts'),'utf8')+fs.readFileSync(path.join(root,'pages/ImagePage.tsx'),'utf8');
const extract=(begin,end)=>transpile(page.slice(page.indexOf(begin),page.indexOf(end,page.indexOf(begin))));
let navigation;
const savedPositions=[];
const dependencies={...utils,useCallback:fn=>fn,navigate:(url,options)=>{navigation={url,options};},restoreScrollPosition:()=>{},saveImagePageScroll:(location,scroller)=>savedPositions.push({location,scroller}),scrollRef:{current:{scrollTop:350}},images:[photoA,photoB],locationWithState:{...stale,state:normalized.options.state},generateImageSlug:(_title,id)=>id.slice(-12)};
const selectContext={...dependencies};
vm.runInNewContext(extract('  const handleImageSelect =','  const handleDownload =')+'\nselect=handleImageSelect;',selectContext);
selectContext.select(photoB);
assert.equal(savedPositions.length,1,'save B before keyboard/arrow selection opens M');
assert.equal(navigation.options.state.background.pathname,'/photos/a');
assert.equal(navigation.options.state.background.state.background,undefined);
assert.equal(navigation.options.replace,false,'standalone A must remain in history when opening B');
const backContext={...dependencies,locationWithState:{pathname:'/photos/b',state:navigation.options.state}};
vm.runInNewContext(extract('  const handleClose =','  const handleOverlayClick =')+'\nclose=handleClose;',backContext);
backContext.close();
assert.equal(navigation.url,-1,'close B should use the preserved A history entry');
utils.setModalActive();
const closeContext={...dependencies,locationWithState:{pathname:'/photos/b',state:{inlineModal:true,background:utils.getImageNavigationBackground(dependencies.locationWithState)}}};
vm.runInNewContext(extract('  const handleClose =','  const handleOverlayClick =')+'\nclose=handleClose;',closeContext);
closeContext.close();
assert.equal(navigation.url,'/photos/a?source=test#details','close B must return to refreshed A, including query/hash');
assert.equal(navigation.options.state.image._id,photoA._id);
assert.equal(navigation.options.replace,true);
const relatedContext={...dependencies};
vm.runInNewContext(extract('  const handleImageSelect =','  const handleDownload =')+'\nselect=handleImageSelect;',relatedContext);
assert.ok(page.includes('onImageClick={handleImageSelect}'),'I cards must use the same handler as keyboard/arrows');
relatedContext.select(photoB,0);
assert.equal(savedPositions.length,2,'save the latest position when reopening from I');
assert.equal(navigation.options.replace,false);
assert.equal(navigation.options.state.background.pathname,'/photos/a');
assert.equal(navigation.options.state.returnToBackgroundInHistory,true);
const nestedContext={...relatedContext,locationWithState:{...stale,pathname:'/photos/b',state:navigation.options.state}};
vm.runInNewContext(extract('  const handleImageSelect =','  const handleDownload =')+'\nselect=handleImageSelect;',nestedContext);
nestedContext.select(photoA,0);
assert.equal(savedPositions.length,2,'changing images inside M must not overwrite B position');
assert.equal(navigation.options.state.image._id,photoA._id,'the selected image must always use the state fast path');
const outside={_id:'000000000000000000000003',imageTitle:'Outside current list'};
selectContext.select(outside);
assert.equal(navigation.options.state.images.length,3);
assert.equal(navigation.options.state.image._id,outside._id);
let listeners=0;
const keyboard=extract('  // Keyboard navigation','  // Handle related image hover');
const keyboardContext={useEffect:fn=>fn(),isBackgroundRoute:true,currentImageIndex:0,images:[photoA,photoB],handleImageSelect:()=>{},handleClose:()=>{},handleToggleFavorite:()=>{},showDownloadMenu:false,showEditModal:false,showCollectionModal:false,window:{addEventListener:()=>listeners++,removeEventListener:()=>{}}};
vm.runInNewContext(keyboard,keyboardContext);
assert.equal(listeners,0,'background photo must not receive Escape or arrow navigation');
vm.runInNewContext(keyboard,{...keyboardContext,isBackgroundRoute:false});
assert.equal(listeners,1);
utils.setModalActive();
const gridClose={...dependencies,locationWithState:{pathname:'/photos/b',state:{inlineModal:true,background:home}}};
vm.runInNewContext(extract('  const handleClose =','  const handleOverlayClick =')+'\nclose=handleClose;',gridClose);
gridClose.close();
assert.equal(navigation.url,'/?category=landscape#grid','grid modal must return to original filtered grid');
console.log('Image navigation: refresh state synchronization, history index, A→B→close A, query/hash and grid return passed.');

